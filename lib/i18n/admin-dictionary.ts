export type AdminKey = keyof typeof adminDict;

/** Date-fns style locale tag for `toLocaleDateString` etc. */
export function localeTag(lang: Lang): string {
  return lang === "gu" ? "gu-IN" : "en-IN";
}

export function at(key: AdminKey, lang: Lang): string {
  const row = adminDict[key];
  if (!row) return String(key);
  return lang === "gu" ? row.gu : row.en;
}

/**
 * Admin-side translator. Reads the same LangProvider the member app uses, so
 * there is exactly one language preference per browser.
 *
 * `t("key")` → string · `tf("key", { n: 5 })` → substitutes `{n}` placeholders.
 */
export function useAdminT() {
  const { lang, setLang } = useLang();

  const t = useCallback((key: AdminKey) => at(key, lang), [lang]);

  const tf = useCallback(
    (key: AdminKey, vars: Record<string, string | number>) =>
      at(key, lang).replace(/\{(\w+)\}/g, (m, name) =>
        name in vars ? String(vars[name]) : m,
      ),
    [lang],
  );

  const locale = useMemo(() => localeTag(lang), [lang]);

  return { t, tf, lang, setLang, locale };
}
