/**
 * Every country a phone number can belong to: name, ISO-3166 alpha-2, dial code,
 * and one real sample number that doubles as the input mask.
 *
 * The list is the 193 UN member states. The ISO code is what picks the flag and
 * what gets stored — dial codes are NOT unique (+1 is the US, Canada and a dozen
 * Caribbean states), so a number identified by its dial code alone cannot be
 * traced back to a country.
 *
 * Sample numbers come from the reference picker in the project brief; each one is
 * turned into a mask by replacing its digits, so the mask also fixes the expected
 * digit count for that country.
 */
export type Country = {
  /** English name, also what the NRI directory groups by. */
  name: string;
  /** ISO-3166 alpha-2, lowercase. The stored value and the flag key. */
  iso: string;
  /** Dial code including the leading +. */
  dial: string;
  /** A real, correctly-formatted sample number for this country. */
  sample: string;
};

